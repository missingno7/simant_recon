static int overview_scale(int profile, uint8_t *scale)
{
    switch (profile) {
    case 0: case 8: case 3: case 5: case 7:
        *scale = 4;
        return 1;
    case 2: case 4:
        *scale = 2;
        return 1;
    default:
        return 0;
    }
}

/* Source-normalized 4x4 selector tiles from S00 m3126's g_1F9E path.
 * Selectors 0..15 are four row bits selecting color 15 over 0.  Selectors
 * 16..23 use the source's alternating EGA colors 0xA/0x5.  These are
 * normalized indexed pixels, not copied display-driver table bytes. */
static int selector_row(uint8_t selector, unsigned row, uint16_t *pixels)
{
    static const uint16_t extended[8][4] = {
        {0xffff, 0xa5a5, 0x0000, 0xa5a5},
        {0xffff, 0xa5a5, 0x0000, 0xa5a5},
        {0xffff, 0x0000, 0x0000, 0x0000},
        {0xa5a5, 0x5a5a, 0x0000, 0x0000},
        {0x0000, 0xffff, 0x0000, 0x0000},
        {0x5a5a, 0xffff, 0x0000, 0x0000},
        {0xffff, 0xffff, 0x0000, 0x0000},
        {0xa5a5, 0xa5a5, 0x5a5a, 0x0000}
    };
    if (pixels == 0 || row >= 4 || selector > 23)
        return 0;
    if (selector < 16)
        *pixels = (selector & (1u << row)) ? 0xffff : 0x0000;
    else
        *pixels = extended[selector - 16u][row];
    return 1;
}

static const uint8_t *select_pheromone(const SimGameWorld *world, int mode)
{
    switch (mode) {
    case 4: return &world->pheromone_b_nest[0][0];
    case 5: return &world->pheromone_b_trail[0][0];
    case 6: return &world->pheromone_r_nest[0][0];
    case 7: return &world->pheromone_r_trail[0][0];
    case 8: return &world->pheromone_a[0][0];
    default: return 0;
    }
}

SimOverviewStatus sim_overview_prepare(const SimOverviewInput *input,
                                       SimOverviewImage *image)
{
    const SimGameWorld *world;
    const uint8_t *life, *map, *pheromone;
    const uint8_t *terrain_table, *life_table;
    int profile, x, y, c, fresh;
    uint8_t preserved[SIM_OVERVIEW_MAX_PIXELS];
    uint8_t scale;
    if (input == 0 || image == 0 || input->world == 0)
        return SIM_OVERVIEW_INVALID_ARGUMENT;
    if (!overview_scale(input->hardware_profile, &scale))
        return SIM_OVERVIEW_UNSUPPORTED_PROFILE;
    if (input->mode < 1 || input->mode > 8)
        return SIM_OVERVIEW_UNSUPPORTED_MODE;
    if (input->fresh && input->mode == input->previous_mode &&
        input->previous_pixels == 0)
        return SIM_OVERVIEW_INVALID_ARGUMENT;
    fresh = input->fresh && input->mode == input->previous_mode;
    if (fresh)
        memmove(preserved, input->previous_pixels, sizeof preserved);
    else
        memset(preserved, 0, sizeof preserved);
    memset(image, 0, sizeof(*image));
    world = input->world;
    profile = input->hardware_profile;
    image->mode = (uint8_t)input->mode;
    image->hardware_profile = input->hardware_profile;
    image->scale_x = scale;
    image->scale_y = scale;
    image->stride = 128;
    image->width = 128;
    image->height = 64;
    memcpy(image->pixels, preserved, sizeof preserved);
    if (input->mode == 1) {
        life = &world->life_a[0][0];
        map = &world->tiles.surface[0][0];
        if ((profile & 1) != 0) {
            terrain_table = world->tiles.terrain_set == 1 ? fd_3D57_054E : fd_3D57_04CE;
            life_table = fd_3D57_061E;
        } else {
            terrain_table = world->tiles.terrain_set == 1 ? fd_3D57_039E : fd_3D57_030E;
            life_table = fd_3D57_046E;
        }
        for (y = 0; y < 64; ++y) {
            for (x = 0; x < 128; ++x) {
                size_t source_index = (size_t)x * 64u + (size_t)y;
                size_t dest_index = (size_t)y * 128u + (size_t)x;
                c = life[source_index];
                if (c != 0)
                    image->pixels[dest_index] = life_table[(unsigned)c >> 3];
                else if (!fresh)
                    image->pixels[dest_index] = terrain_table[map[source_index]];
            }
        }
        return SIM_OVERVIEW_OK;
    }
    if (input->mode == 2 || input->mode == 3) {
        if (input->mode == 3) {
            life = &world->life_r[0][0];
            map = &world->tiles.nest_r[0][0];
        } else {
            life = &world->life_b[0][0];
            map = &world->tiles.nest_b[0][0];
        }
        image->width = 64;
        image->height = 64;
        image->stride = 64;
        image->left_margin = (uint16_t)(scale * 32u);
        if ((profile & 1) != 0) {
            for (y = 0; y < 64; ++y) for (x = 0; x < 64; ++x) {
                size_t i = (size_t)y * 64u + (size_t)x;
                c = life[(size_t)x * 64u + (size_t)y];
                if (c == 0) {
                    if (!fresh) image->pixels[i] = fd_3D57_0656[map[(size_t)x * 64u + (size_t)y] >> 2];
                } else if (c == 0xfe || c == 0xff) image->pixels[i] = 0x27;
                else image->pixels[i] = (c & 0x80) ? 0x25 : 0x23;
            }
        } else {
            for (y = 0; y < 64; ++y) for (x = 0; x < 64; ++x) {
                size_t i = (size_t)y * 64u + (size_t)x;
                c = life[(size_t)x * 64u + (size_t)y];
                if (c == 0) {
                    if (!fresh) image->pixels[i] = fd_3D57_04A6[map[(size_t)x * 64u + (size_t)y] >> 2];
                } else if (c == 0xfe || c == 0xff) image->pixels[i] = 1;
                else image->pixels[i] = (c & 0x80) ? 3 : 0x0f;
            }
        }
        return SIM_OVERVIEW_OK;
    }
    pheromone = select_pheromone(world, input->mode);
    if (pheromone == 0)
        return SIM_OVERVIEW_UNSUPPORTED_MODE;
    for (x = 0; x < 32; ++x) for (y = 0; y < 64; ++y) {
        uint8_t c = pheromone[(size_t)y * 32u + (size_t)x];
        size_t i = ((size_t)x * 128u + (size_t)y) * 2u;
        c = c ? (uint8_t)(((profile & 1) ? (c >> 4) + 0x2e : (c >> 5) + 0x10)) : (uint8_t)((profile & 1) ? 0 : 0x0b);
        image->pixels[i] = c;
        image->pixels[i + 1] = c;
        image->pixels[i + 128u] = c;
        image->pixels[i + 129u] = c;
    }
    return SIM_OVERVIEW_OK;
}

SimOverviewStatus sim_overview_blit(const SimOverviewImage *image,
                                    PortableFramebuffer *framebuffer,
                                    int32_t left,
                                    int32_t top)
{
    int32_t x, y, tx, ty;
    if (image == 0 || framebuffer == 0 || framebuffer->pixels == 0 ||
        image->width == 0 || image->height == 0 || image->stride < image->width ||
        (image->hardware_profile != 0 && image->hardware_profile != 8))
        return SIM_OVERVIEW_UNSUPPORTED_PROFILE;
    if (image->scale_x != 4 || image->scale_y != 4 ||
        (size_t)(image->height - 1u) * image->stride + image->width > sizeof(image->pixels))
        return SIM_OVERVIEW_INVALID_ARGUMENT;
    for (y = 0; y < image->height; ++y)
        for (x = 0; x < image->width; ++x)
            if (image->pixels[(size_t)y * image->stride + (size_t)x] > 23)
                return SIM_OVERVIEW_UNSUPPORTED_SELECTOR;
    for (y = 0; y < image->height; ++y) {
        for (x = 0; x < image->width; ++x) {
            uint8_t selector = image->pixels[(size_t)y * image->stride + (size_t)x];
            for (ty = 0; ty < 4; ++ty) {
                uint16_t row_pixels;
                if (!selector_row(selector, (unsigned)ty, &row_pixels))
                    return SIM_OVERVIEW_UNSUPPORTED_SELECTOR;
                for (tx = 0; tx < 4; ++tx) {
                    uint8_t color = (uint8_t)((row_pixels >>
                                               ((unsigned)(3 - tx) * 4u)) & 0x0fu);
                    portable_put_pixel(framebuffer,
                                       left + image->left_margin + x * 4 + tx,
                                       top + y * 4 + ty, color);
                }
            }
        }
    }
    return SIM_OVERVIEW_OK;
}
