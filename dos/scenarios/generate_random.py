"""Write deterministic Quick Game input; see corpus.md for domain and recipe."""
import argparse
from pathlib import Path


def generate(seed):
    state=seed & 0xffffffff
    rows=[]
    def sample(n):
        nonlocal state
        state=(1664525*state+1013904223) & 0xffffffff
        return state % n
    def add(t,command):rows.append((t,command))
    def chord(t,modifier,key):
        add(t,'keydown '+modifier);add(t+100,'key '+key);add(t+300,'keyup '+modifier)
    def point(t,x,y):
        add(t,'mouse_move -1280 -960');add(t+100,f'mouse_move {2*x} {2*y}')
    def click(t,x,y,button=0):
        point(t,x,y);add(t+300,f'mouse_button {button} down');add(t+450,f'mouse_button {button} up')
    for t in (5000,7000,9000):add(t,'key enter')
    click(12000,370,165)
    add(16000,'key enter');add(20000,'key enter')
    chord(22000,'lctrl','e')
    # No File menu, quit keys, pause shortcut or clicks in the menu bar.
    # Rectangles stay inside the original edit/map playfields, away from Pause.
    for t in range(25000,350000,2000):
        operation=sample(7)
        x,y=90+sample(310),100+sample(220)
        if operation in (0,1):click(t,x,y)
        elif operation==2:
            click(t,x,y)
            add(t+520,'mouse_button 0 down');add(t+600,'mouse_button 0 up')
        elif operation==3:point(t,x,y)
        elif operation==4:add(t,'key '+('home','0','1','2','3','4','tab')[sample(7)])
        elif operation==5:chord(t,'lctrl',('e','m','i','h','b','c','8','9','0')[sample(9)])
        else:click(t,x,y,1)
        add(t+1200,'key enter')
    # Dialog dismissal continues until the observer reaches its entry bound.
    for t in range(355000,601000,5000):add(t,'key enter')
    add(610000,'exit')
    rows.sort()
    return f'# Generated by generate_random.py --seed {seed}; LCG32, see corpus.md.\n'+''.join(f'{t} {op}\n' for t,op in rows)


def main():
    ap=argparse.ArgumentParser(description=__doc__)
    ap.add_argument('--seed',type=int,required=True)
    ap.add_argument('--out',type=Path,required=True)
    args=ap.parse_args()
    args.out.write_text(generate(args.seed))


if __name__=='__main__':main()
